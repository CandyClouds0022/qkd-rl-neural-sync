        if not os.path.exists(out_dir): #in case folder does not exist allready
            os.makedirs(out_dir) #create it
            print(f"Directory '{out_dir}' created.")
        for l in L:
            self.L=l
            self.chloss=1-10**((-self.L*0.2)/10) #calcolo della perdita in base alla distanza L 
            print(f"Generating dataset for distance {l} km (Loss={self.chloss:.4f})...")
            for i in range(n_samples_per_distance):
            #NextEngine: current_bias=np.random.uniform(0.1, 0.9)
                current_bias=0.5 #BIAS FIXED for BASELINE
                #current_loss=np.random.uniform(0.0, 0.5) #variation for less dummy model
                self.bias=current_bias
                A_bits, A_bases=self.generate_Alice()
                out_bits, out_bases=self.channel_simulation(A_bases, A_bits)
