"""
Model for QKD simulation based on BB84 protocol, in the most essential form.
Class designed for the environment.py to inherit from. The physical engine in the advanced version 
will inherit Alice's generation without operating modifications on it.

Main actions of the current engine:
- Alice generation=> bit and bias basis generation
- channel simulation=> Eve doing Evel things
- sifting=> basis reconciliation, wrong bits get discarded

A static dataset can be generated for physicalengine type objects, with a dedicated function 
(the last cited below).
"""

